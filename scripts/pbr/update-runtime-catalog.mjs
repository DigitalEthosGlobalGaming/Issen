import { readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

async function existing(root, names, required = true) {
  for (const name of names) {
    try { await access(path.join(root, name)); return name; } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  if (required) throw new Error(`Missing runtime plane: ${names.join(' or ')}`);
}

export async function generateRuntimeCatalog(root = path.resolve(import.meta.dirname, '../..')) {
  const jobs = JSON.parse(await readFile(path.join(root, 'scripts/pbr/asset-packs.json'), 'utf8'));
  const entries = Array.isArray(jobs) ? jobs : [...jobs.assets, ...(jobs.installed ?? [])];
  const relative = (p) => './' + path.relative(path.join(root, 'src/rendering'), path.join(root,p)).replaceAll('\\','/');
  const lines = [
    '// Generated by scripts/pbr/update-runtime-catalog.mjs. Do not edit by hand.',
    "import type { PbrAtlasSources } from './pbr-atlas.ts';",
    'interface AssetMaterialPack { sourcePath: string; source: string; dimensions: readonly [number, number]; maps: PbrAtlasSources; }',
    'export const assetMaterialCatalog: readonly AssetMaterialPack[] = [',
  ];
  for (const job of entries) {
    const pack = job.dimensions ? job : JSON.parse(await readFile(path.join(root, job.output, 'generation.json'), 'utf8'));
    const stem = path.basename(pack.source, '.png');
    const source = await existing(root, [pack.source.replace(/\.png$/, '.webp'), pack.source]);
    lines.push(`{ sourcePath: ${JSON.stringify(pack.source)}, source: new URL(${JSON.stringify(relative(source))}, import.meta.url).href, dimensions: [${pack.dimensions}] as const, maps: {`);
    for (const kind of ['diffuse','normal','surface','emissive']) {
      const plane = await existing(root, ['webp','png'].map(ext => `${pack.output}/${stem}_${kind}.${ext}`), kind !== 'emissive');
      if (plane) lines.push(`${kind}: new URL(${JSON.stringify(relative(plane))}, import.meta.url).href,`);
    }
    lines.push('} },');
  }
  lines.push('];');
  const output = lines.join('\n')+'\n';
  await writeFile(path.join(root,'src/rendering/asset-material-catalog.ts'),output);
  return output;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generateRuntimeCatalog();
